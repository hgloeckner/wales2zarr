def open_wales():
    full_datasets = {}
    names = ["bsri", "bsrgu", "bsrgul", "bsrgl", "bsrg", "adepg", "adepgl", "tau2gl"]
    var_names = [
        "backscatter_ratio",
        "backscatter_ratio",
        "backscatter_ratio",
        "backscatter_ratio",
        "backscatter_ratio",
        "particle_depolarisation",
        "particle_depolarisation",
        "two_way_aerosol_optical_transmission",
    ]

    for name, var_name in zip(names, var_names):
        full_datasets[name] = get_full_ds_for_var(name, var_name)
    ds = xr.merge(full_datasets.values())
    print("ds merged", flush=True)
    return ds.pipe(bitround).chunk(time=-1, altitude=-1)


def write_wales(store):
    wales = open_wales()

    wales.attrs = wales_attrs = {
        "title": "WALES L1 on a common altitude",
        "creator_name": "Martin Wirth",
        "creator_email": "martin.wirth@dlr.de",
        "convention": "CF-1.8",
        "data_version": "1.0",
        "featureType": "trajectory",
        "institution": "Deutsches Zentrum fuer Luft- und Raumfahrt, Institut fuer Physik der Atmosphaere, Oberpfaffenhofen, Muenchener Str. 20, 82234 Wessling, Germany",
        "source": "DLR-Lidar observation",
        "location_name": "DLR-WALES on HALO (D-ADLR)",
        "instrument": "WALES",
        "comment": "Version 1 preliminary",
        "history": "2024-10-16T09:07:17 Generated by DLRLidar.jl tools suite",
        "platform": "HALO",
        "project": "PERCUSION",
    }
    wales.to_zarr(
        store,
        encoding=get_encoding(wales),
        mode="w",
    )


def _main():

    parser = argparse.ArgumentParser(description="Create wales.")
    parser.add_argument("-s", "--store", type=str)

    args = parser.parse_args()

    write_wales(args.store)


if __name__ == "__main__":
    _main()
