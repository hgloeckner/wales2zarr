from myutils import get_encoding, get_full_ds_for_var, bitround


def open_wales_wv(path):
    ds = get_full_ds_for_var(path, "wv", "water_vapor_molecular_density")
    print("wv opened", flush=True)
    return ds.pipe(bitround).chunk(time=-1, altitude=-1)


def write_wv(path, store):
    wales = open_wales_wv(path)

    wales.attrs = {
        "title": "WALES L1 on a common altitude (water vapor)",
        "creator_name": "Martin Wirth",
        "creator_email": "martin.wirth@dlr.de",
        "convention": "CF-1.8",
        "data_version": "1.2",
        "featureType": "trajectory",
        "institution": "Deutsches Zentrum fuer Luft- und Raumfahrt, Institut fuer Physik der Atmosphaere, Oberpfaffenhofen, Muenchener Str. 20, 82234 Wessling, Germany",
        "source": "DLR-Lidar observation",
        "location_name": "DLR-WALES on HALO (D-ADLR)",
        "instrument": "WALES",
        "history": "unified to zarr by Helene Gloeckner \n 2025-05-12T13:14:48 Generated by DLRLidar.jl tools suite",
        "platform": "HALO",
        "project": "PERCUSION",
        "references": "doi.org/10.5194/amt-19-3933-2026",
    }
    wales.to_zarr(
        store,
        encoding=get_encoding(wales),
        mode="w",
    )


def _main():
    parser = argparse.ArgumentParser(description="Create wales.")
    parser.add_argument("-s", "--store", type=str)
    parser.add_argument("-p", "--path", type=str)

    args = parser.parse_args()

    write_wv(args.path, args.store)


if __name__ == "__main__":
    _main()
